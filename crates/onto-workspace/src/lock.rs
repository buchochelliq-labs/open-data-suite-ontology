//! `onto.lock`: pins central sources so every checkout and CI run sees the same ontology.

use std::path::Path;

use serde::{Deserialize, Serialize};

pub const LOCK_FILE: &str = "onto.lock";

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Lock {
    pub version: u32,
    #[serde(default, rename = "source")]
    pub sources: Vec<LockedSource>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct LockedSource {
    pub id: String,
    pub url: String,
    pub commit: String,
}

impl Lock {
    pub fn read(root: &Path) -> std::io::Result<Option<Lock>> {
        let path = root.join(LOCK_FILE);
        if !path.exists() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(path)?;
        toml::from_str(&text).map(Some).map_err(std::io::Error::other)
    }

    pub fn write(&self, root: &Path) -> std::io::Result<()> {
        let body = toml::to_string(self).map_err(std::io::Error::other)?;
        std::fs::write(root.join(LOCK_FILE), format!("# Generated by `onto sync`. Commit this file.\n{body}"))
    }

    pub fn get(&self, id: &str, url: &str) -> Option<&LockedSource> {
        self.sources.iter().find(|s| s.id == id && s.url == url)
    }
}
